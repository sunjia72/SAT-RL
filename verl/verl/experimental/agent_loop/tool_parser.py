import json
import logging
import os
from abc import ABC, abstractmethod
from typing import Any, Optional

import regex
from pydantic import BaseModel, Field

from verl.tools.schemas import OpenAIFunctionToolSchema
from verl.utils.ray_utils import get_event_loop
from verl.utils.rollout_trace import rollout_trace_op

logger = logging.getLogger(__file__)
logger.setLevel(os.getenv("VERL_LOGGING_LEVEL", "WARN"))


class ToolCallValidationError(BaseModel):
    """A parser-side validation error that can be surfaced without executing a call."""

    code: str
    message: str
    parameter: str | None = None


class FunctionCall(BaseModel):
    arguments: str
    """
    The arguments to call the function with, as generated by the model in JSON
    format. Note that the model does not always generate valid JSON, and may
    hallucinate parameters not defined by your function schema. Validate the
    arguments in your code before calling your function.
    """

    name: str
    """The name of the function to call."""

    validation_errors: list[ToolCallValidationError] = Field(default_factory=list)
    """Schema and syntax errors found while parsing the generated call."""

    raw_call: str | None = None
    """The generated call body, retained for diagnostics when parsing fails."""

    @property
    def is_valid(self) -> bool:
        """Whether the call passed parser-side syntax and schema validation."""
        return not self.validation_errors


class ToolParser(ABC):
    _registry: dict[str, type["ToolParser"]] = {}

    def __init__(self, tokenizer) -> None:
        self.tokenizer = tokenizer

    @staticmethod
    def _validate_function_call(
        function_call: FunctionCall, tools: Optional[list[OpenAIFunctionToolSchema]]
    ) -> FunctionCall:
        """Validate a parsed call without changing generated names or values.

        ``tools=None`` means that no schemas were supplied, so only the JSON
        argument shape can be checked. An explicitly empty list means that no
        function names are allowed.
        """
        errors = list(function_call.validation_errors)
        try:
            arguments = json.loads(function_call.arguments)
        except (TypeError, json.JSONDecodeError) as exc:
            errors.append(
                ToolCallValidationError(
                    code="invalid_arguments",
                    message=f"Tool arguments are not valid JSON: {exc}",
                )
            )
            return function_call.model_copy(update={"validation_errors": errors})

        if not isinstance(arguments, dict):
            errors.append(
                ToolCallValidationError(
                    code="invalid_arguments",
                    message="Tool arguments must decode to a JSON object.",
                )
            )
            return function_call.model_copy(update={"validation_errors": errors})

        if tools is None:
            return function_call.model_copy(update={"validation_errors": errors})

        schema = next(
            (tool for tool in tools if tool.type == "function" and tool.function.name == function_call.name),
            None,
        )
        if schema is None:
            allowed_names = [tool.function.name for tool in tools if tool.type == "function"]
            errors.append(
                ToolCallValidationError(
                    code="invalid_tool_name",
                    message=(f"Unknown tool name {function_call.name!r}. Allowed names: {allowed_names or 'none'}."),
                )
            )
            return function_call.model_copy(update={"validation_errors": errors})

        parameters = schema.function.parameters
        properties = parameters.properties
        for parameter_name in arguments.keys() - properties.keys():
            errors.append(
                ToolCallValidationError(
                    code="unknown_parameter",
                    message=(f"Parameter {parameter_name!r} is not defined for tool {function_call.name!r}."),
                    parameter=parameter_name,
                )
            )

        for parameter_name in parameters.required:
            if parameter_name not in arguments:
                errors.append(
                    ToolCallValidationError(
                        code="missing_required_parameter",
                        message=(f"Required parameter {parameter_name!r} is missing for tool {function_call.name!r}."),
                        parameter=parameter_name,
                    )
                )

        for parameter_name, value in arguments.items():
            property_schema = properties.get(parameter_name)
            if property_schema is None:
                continue

            expected_type = property_schema.type.strip().lower()
            type_matches = {
                "array": lambda candidate: isinstance(candidate, list),
                "boolean": lambda candidate: isinstance(candidate, bool),
                "integer": lambda candidate: isinstance(candidate, int) and not isinstance(candidate, bool),
                "null": lambda candidate: candidate is None,
                "number": lambda candidate: isinstance(candidate, int | float) and not isinstance(candidate, bool),
                "object": lambda candidate: isinstance(candidate, dict),
                "string": lambda candidate: isinstance(candidate, str),
            }.get(expected_type)
            if type_matches is not None and not type_matches(value):
                errors.append(
                    ToolCallValidationError(
                        code="invalid_parameter_type",
                        message=(
                            f"Parameter {parameter_name!r} for tool {function_call.name!r} "
                            f"must have type {expected_type!r}."
                        ),
                        parameter=parameter_name,
                    )
                )
                continue

            if property_schema.enum is not None and value not in property_schema.enum:
                errors.append(
                    ToolCallValidationError(
                        code="invalid_parameter_value",
                        message=(
                            f"Parameter {parameter_name!r} for tool {function_call.name!r} "
                            f"must be one of {property_schema.enum!r}."
                        ),
                        parameter=parameter_name,
                    )
                )

        return function_call.model_copy(update={"validation_errors": errors})

    def get_tool_format_instruction(self, tools: Optional[list[OpenAIFunctionToolSchema]]) -> str | None:
        """Return optional schema-specific format guidance for a prompt."""
        return None

    @abstractmethod
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        """Extract tool calls from the responses.

        Args:
            responses_ids (List[int]): The ids of the responses.
            tools (List[OpenAIFunctionToolSchema], optional): OpenAI function tool schema.

        Returns:
            Tuple[str, List[FunctionCall]]: Content and extracted tool calls.
        """
        raise NotImplementedError

    @classmethod
    def get_tool_parser(cls, name: str, tokenizer):
        if name not in cls._registry:
            raise ValueError(f"Unknown tool parser: {name}")
        return cls._registry[name](tokenizer)

    @classmethod
    def register(cls, name: str):
        def decorator(subclass: type[ToolParser]) -> type[ToolParser]:
            cls._registry[name] = subclass
            return subclass

        return decorator


@ToolParser.register("hermes")
class HermesToolParser(ToolParser):
    """Adapted from https://github.com/vllm-project/vllm/blob/v0.9.1/vllm/entrypoints/openai/tool_parsers/hermes_tool_parser.py"""

    def __init__(self, tokenizer) -> None:
        super().__init__(tokenizer)

        self.tool_call_start_token: str = "<tool_call>"
        self.tool_call_end_token: str = "</tool_call>"
        self.tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        loop = get_event_loop()
        text = await loop.run_in_executor(None, self.tokenizer.decode, responses_ids)
        if self.tool_call_start_token not in text or self.tool_call_end_token not in text:
            return text, []

        matches = self.tool_call_regex.findall(text)
        function_calls = []
        for match in matches:
            try:
                function_call = json.loads(match)
                name, arguments = function_call["name"], function_call["arguments"]
                parsed_call = FunctionCall(
                    name=name,
                    arguments=json.dumps(arguments, ensure_ascii=False),
                    raw_call=match,
                )
                function_calls.append(self._validate_function_call(parsed_call, tools))
            except Exception as e:
                logger.error(f"Failed to decode tool call: {e}")
                function_calls.append(
                    FunctionCall(
                        name="",
                        arguments="{}",
                        raw_call=match,
                        validation_errors=[
                            ToolCallValidationError(
                                code="malformed_tool_call",
                                message=f"Failed to decode tool call: {e}",
                            )
                        ],
                    )
                )

        # remaing text exclude tool call tokens
        content = self.tool_call_regex.sub("", text)

        return content, function_calls


@ToolParser.register("gpt-oss")
class GptOssToolParser(ToolParser):
    """
    Tool parser for gpt-oss model.
    Adapted from https://github.com/sgl-project/sglang/blob/main/python/sglang/srt/function_call/gpt_oss_detector.py

    Args:
        tokenizer: The tokenizer to use.
    """

    def __init__(self, tokenizer) -> None:
        super().__init__(tokenizer)
        # check https://cookbook.openai.com/articles/openai-harmony for more details.
        self.cot_pattern = regex.compile(
            r"<\|start\|>assistant<\|channel\|>analysis<\|message\|>.*?<\|end\|>", regex.DOTALL
        )
        # <|start|>assistant may be pre-appended in prompts, so we need to remove it.
        self.partial_cot_pattern = regex.compile(r"<\|channel\|>analysis<\|message\|>(.*?)<\|end\|>", regex.DOTALL)
        self.tool_call_pattern = regex.compile(
            r"<\|start\|>assistant<\|channel\|>[^<]* to=functions\.([^<]+) "
            r"<\|constrain\|>json<\|message\|>(.*?)<\|call\|>",
            regex.DOTALL,
        )

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        loop = get_event_loop()
        # We need to keep special tokens for gpt-oss model for better tool call extraction.
        text = await loop.run_in_executor(None, lambda: self.tokenizer.decode(responses_ids, skip_special_tokens=False))
        # Need to remove padding tokens for better tool call extraction.
        text = text.replace(self.tokenizer.pad_token, "")
        # Need to reomve COT since COT may contain tool call tokens.But they are not valid tool calls.
        text = regex.sub(self.cot_pattern, "", text)
        text = regex.sub(self.partial_cot_pattern, "", text)

        # check if there are tool calls in the text by re.findall
        matches = regex.findall(self.tool_call_pattern, text)
        if not matches:
            return text, []

        function_calls = []
        for match in matches:
            try:
                name, arguments = match[0], match[1]
                parsed_call = FunctionCall(name=name, arguments=arguments, raw_call=match[1])
                function_calls.append(self._validate_function_call(parsed_call, tools))
            except Exception as e:
                logger.error(f"Failed to decode tool call: {e}")

        # remaing text exclude tool call tokens
        content = regex.sub(self.tool_call_pattern, "", text)

        return content, function_calls


@ToolParser.register("qwen3_coder")
class Qwen3XMLToolParser(ToolParser):
    """
    Tool parser for qwen3_coder/qwen3.5 model.
    Adapted from https://huggingface.co/Qwen/Qwen3-Coder-30B-A3B-Instruct/blob/main/qwen3coder_tool_parser.py

    Args:
        tokenizer: The tokenizer to use.
    """

    def __init__(self, tokenizer):
        super().__init__(tokenizer)

        self.tool_call_start_token: str = "<tool_call>"
        self.tool_call_end_token: str = "</tool_call>"
        self.tool_call_prefix: str = "<function="

        self.tool_call_complete_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)
        self.tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>|<tool_call>(.*?)$", regex.DOTALL)
        self.tool_call_function_regex = regex.compile(r"<function=(.*?)</function>|<function=(.*)$", regex.DOTALL)
        self.tool_call_parameter_regex = regex.compile(
            r"<parameter=([^<>\r\n]+)>(.*?)</parameter>|<parameter=([^<>\r\n]+)>(.*)$",
            regex.DOTALL,
        )

    @staticmethod
    def _xml_parameter_value(param_value: str, param_type: str) -> Any:
        """Decode an XML parameter using JSON-schema scalar/container rules.

        Values that do not decode as the declared type are deliberately kept
        as strings; schema validation then records the type error. This avoids
        silently repairing invalid model output.
        """
        param_type = param_type.strip().lower()
        try:
            if param_type == "integer":
                return int(param_value)
            if param_type == "number":
                return float(param_value)
            if param_type == "boolean":
                if param_value == "true":
                    return True
                if param_value == "false":
                    return False
                return param_value
            if param_type in {"array", "object", "null"}:
                return json.loads(param_value)
        except (TypeError, ValueError, json.JSONDecodeError):
            return param_value
        return param_value

    def _parse_xml_function_call(
        self,
        function_call_str: str,
        tools: Optional[list[OpenAIFunctionToolSchema]],
        *,
        tool_call_complete: bool = True,
        function_complete: bool = True,
    ) -> FunctionCall:
        errors = []
        if not tool_call_complete:
            errors.append(
                ToolCallValidationError(
                    code="malformed_tool_call",
                    message="The <tool_call> element is not closed.",
                )
            )
        if not function_complete:
            errors.append(
                ToolCallValidationError(
                    code="malformed_tool_call",
                    message="The <function> element is not closed.",
                )
            )

        if ">" not in function_call_str:
            errors.append(
                ToolCallValidationError(
                    code="malformed_tool_call",
                    message="The function opening tag is missing its closing '>'.",
                )
            )
            return FunctionCall(
                name="",
                arguments="{}",
                validation_errors=errors,
                raw_call=function_call_str,
            )

        end_index = function_call_str.index(">")
        function_name = function_call_str[:end_index]
        schema = None
        if tools is not None:
            schema = next(
                (tool for tool in tools if tool.type == "function" and tool.function.name == function_name),
                None,
            )
        properties = schema.function.parameters.properties if schema is not None else {}
        parameters = function_call_str[end_index + 1 :]
        param_dict = {}
        cursor = 0
        for match in self.tool_call_parameter_regex.finditer(parameters):
            if parameters[cursor : match.start()].strip():
                errors.append(
                    ToolCallValidationError(
                        code="malformed_tool_call",
                        message="Unexpected text outside a <parameter=...> element.",
                    )
                )

            parameter_complete = match.group(1) is not None
            param_name = match.group(1) if parameter_complete else match.group(3)
            param_value = str(match.group(2) if parameter_complete else match.group(4))
            if not parameter_complete:
                errors.append(
                    ToolCallValidationError(
                        code="malformed_tool_call",
                        message=f"Parameter {param_name!r} is not closed.",
                        parameter=param_name,
                    )
                )
            # Remove prefix and trailing \n
            if param_value.startswith("\n"):
                param_value = param_value[1:]
            if param_value.endswith("\n"):
                param_value = param_value[:-1]

            if param_name in param_dict:
                errors.append(
                    ToolCallValidationError(
                        code="invalid_arguments",
                        message=f"Parameter {param_name!r} was supplied more than once.",
                        parameter=param_name,
                    )
                )
            property_schema = properties.get(param_name)
            param_type = property_schema.type if property_schema is not None else "string"
            param_dict[param_name] = self._xml_parameter_value(param_value, param_type)
            cursor = match.end()

        if parameters[cursor:].strip():
            errors.append(
                ToolCallValidationError(
                    code="malformed_tool_call",
                    message="Unexpected or malformed content in the function body.",
                )
            )

        parsed_call = FunctionCall(
            name=function_name,
            arguments=json.dumps(param_dict, ensure_ascii=False),
            validation_errors=errors,
            raw_call=function_call_str,
        )
        return self._validate_function_call(parsed_call, tools)

    def _get_function_calls(self, model_output: str) -> list[tuple[str, bool, bool]]:
        # Find all tool calls
        matched_ranges = list(self.tool_call_regex.finditer(model_output))
        raw_tool_calls = [
            (match.group(1) if match.group(1) is not None else match.group(2), match.group(1) is not None)
            for match in matched_ranges
        ]

        # Back-off strategy if no tool_call tags found
        if len(raw_tool_calls) == 0:
            raw_tool_calls = [(model_output, False)]

        raw_function_calls = []
        for tool_call, tool_call_complete in raw_tool_calls:
            function_matches = list(self.tool_call_function_regex.finditer(tool_call))
            if not function_matches:
                raw_function_calls.append((tool_call, tool_call_complete, False))
                continue
            raw_function_calls.extend(
                (
                    match.group(1) if match.group(1) is not None else match.group(2),
                    tool_call_complete,
                    match.group(1) is not None,
                )
                for match in function_matches
            )

        return raw_function_calls

    def get_tool_format_instruction(self, tools: Optional[list[OpenAIFunctionToolSchema]]) -> str | None:
        """Build Qwen XML guidance with exact schema names instead of generic placeholders.

        The agent loop may append this text to its system prompt. Keeping prompt
        construction separate avoids mutating tokenizer/model chat templates.
        """
        if not tools:
            return None

        function_tools = [tool for tool in tools if tool.type == "function"]
        if not function_tools:
            return None

        allowed_names = ", ".join(repr(tool.function.name) for tool in function_tools)
        examples = []
        for tool in function_tools:
            parameters = tool.function.parameters
            parameter_names = list(parameters.required)
            if not parameter_names and parameters.properties:
                parameter_names = [next(iter(parameters.properties))]

            lines = ["<tool_call>", f"<function={tool.function.name}>"]
            for parameter_name in parameter_names:
                property_schema = parameters.properties.get(parameter_name)
                if property_schema is None:
                    continue
                example_value = {
                    "array": "[]",
                    "boolean": "true",
                    "integer": "0",
                    "null": "null",
                    "number": "0",
                    "object": "{}",
                }.get(property_schema.type.strip().lower(), "value")
                if parameter_name == "code" and property_schema.type.strip().lower() == "string":
                    example_value = 'print("hello")'
                lines.extend(
                    [
                        f"<parameter={parameter_name}>",
                        example_value,
                        "</parameter>",
                    ]
                )
            lines.extend(["</function>", "</tool_call>"])
            examples.append("\n".join(lines))

        return (
            "Use only the exact function and parameter names shown in the tool schemas. "
            f"Allowed function names: {allowed_names}.\n\n"
            "Valid XML example(s):\n" + "\n\n".join(examples)
        )

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        loop = get_event_loop()
        text = await loop.run_in_executor(None, self.tokenizer.decode, responses_ids)
        if self.tool_call_start_token not in text:
            return text, []

        try:
            function_calls = self._get_function_calls(text)
            if len(function_calls) == 0:
                return text, []

            tool_calls = []
            for function_call_str, tool_call_complete, function_complete in function_calls:
                try:
                    tool_calls.append(
                        self._parse_xml_function_call(
                            function_call_str,
                            tools,
                            tool_call_complete=tool_call_complete,
                            function_complete=function_complete,
                        )
                    )
                except Exception as exc:
                    logger.exception(f"Error in extracting tool call from response: {exc}")
                    tool_calls.append(
                        FunctionCall(
                            name="",
                            arguments="{}",
                            raw_call=function_call_str,
                            validation_errors=[
                                ToolCallValidationError(
                                    code="malformed_tool_call",
                                    message=f"Failed to parse tool call: {exc}",
                                )
                            ],
                        )
                    )

            # Extract content before tool calls
            content_index = text.find(self.tool_call_start_token)
            content_index = content_index if content_index >= 0 else text.find(self.tool_call_prefix)
            content = text[:content_index]  # .rstrip()

            return content, tool_calls
        except Exception as e:
            logger.exception(f"Error in extracting tool call from response: {e}")
            return text, []
